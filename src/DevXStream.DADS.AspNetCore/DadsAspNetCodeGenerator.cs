using System.Text;
using DevXStream.DADS.Models;
using Microsoft.AspNetCore.Http;

namespace DevXStream.DADS.AspNetCore;

/// <summary>Generates compile-time ASP.NET Core endpoint contracts from a DADS definition.</summary>
public static class DadsAspNetCodeGenerator
{
    /// <summary>Generates endpoint interfaces and route registration code for a validated definition.</summary>
    public static string Generate(DadsDefinition definition, string namespaceName = "Dads.Generated")
    {
        ArgumentNullException.ThrowIfNull(definition);
        ArgumentException.ThrowIfNullOrWhiteSpace(namespaceName);

        var operations = definition.Modules.SelectMany(module => module.Endpoints.Select(operation => new GeneratedOperation(module.Name, operation))).ToArray();
        var duplicateInterfaces = operations.GroupBy(operation => InterfaceName(operation.Operation), StringComparer.Ordinal)
            .Where(group => group.Count() > 1).Select(group => group.Key).ToArray();
        if (duplicateInterfaces.Length > 0)
            throw new InvalidOperationException($"DADS operations generate duplicate handler interfaces: {string.Join(", ", duplicateInterfaces)}.");

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("using System;");
        source.AppendLine("using System.Threading.Tasks;");
        source.AppendLine("using DevXStream.DADS.AspNetCore;");
        source.AppendLine("using Microsoft.AspNetCore.Builder;");
        source.AppendLine("using Microsoft.AspNetCore.Http;");
        source.AppendLine("using Microsoft.AspNetCore.Routing;");
        source.AppendLine();
        source.Append("namespace ").Append(namespaceName).AppendLine(";");
        source.AppendLine();

        foreach (var operation in operations)
            source.Append("public interface ").Append(InterfaceName(operation.Operation)).AppendLine(" : IDadsGeneratedOperationHandler { }");

        source.AppendLine();
        source.AppendLine("public static class DadsGeneratedEndpointRouteBuilderExtensions");
        source.AppendLine("{");
        source.AppendLine("    public static IEndpointRouteBuilder MapGeneratedDadsEndpoints(this IEndpointRouteBuilder endpoints)");
        source.AppendLine("    {");
        source.AppendLine("        ArgumentNullException.ThrowIfNull(endpoints);");
        foreach (var operation in operations)
        {
            var interfaceName = InterfaceName(operation.Operation);
            source.Append("        Func<HttpContext, ").Append(interfaceName).Append(", Task<IResult>> ")
                .Append(LocalHandlerName(operation.Operation)).Append(" = (context, handler) => handler.HandleAsync(context, context.RequestAborted);").AppendLine();
            source.Append("        endpoints.MapMethods(\"").Append(Escape(operation.Operation.Route)).Append("\", [\"")
                .Append(Escape(operation.Operation.Method.ToUpperInvariant())).Append("\"], (Delegate)").Append(LocalHandlerName(operation.Operation)).Append(")").AppendLine();
            source.Append("            .WithName(\"").Append(Escape(operation.Operation.Name)).Append("\")").AppendLine();
            source.Append("            .WithDisplayName(\"DADS: ").Append(Escape(operation.Operation.Name)).Append("\")").AppendLine();
            source.Append("            .WithMetadata(new DadsGeneratedOperationMetadata(\"").Append(Escape(operation.ModuleName)).Append("\", \"")
                .Append(Escape(operation.Operation.Name)).Append("\"));").AppendLine();
        }
        source.AppendLine("        return endpoints;");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string InterfaceName(OperationDefinition operation) => "I" + Identifier(operation.Engineering?.Handler ?? operation.Name + "Handler");
    private static string LocalHandlerName(OperationDefinition operation) => "map" + Identifier(operation.Name);
    private static string Identifier(string value)
    {
        var result = new StringBuilder();
        foreach (var character in value)
            result.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        if (result.Length == 0 || char.IsDigit(result[0])) result.Insert(0, '_');
        else result[0] = char.ToUpperInvariant(result[0]);
        return result.ToString();
    }
    private static string Escape(string value) => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

    private sealed record GeneratedOperation(string ModuleName, OperationDefinition Operation);
}

/// <summary>Common contract implemented by code-generated DADS operation handlers.</summary>
public interface IDadsGeneratedOperationHandler
{
    /// <summary>Handles an HTTP request for a generated DADS operation.</summary>
    Task<IResult> HandleAsync(HttpContext httpContext, CancellationToken cancellationToken);
}

/// <summary>Metadata retained on an endpoint generated from a DADS operation.</summary>
public sealed record DadsGeneratedOperationMetadata(string ModuleName, string OperationName);
